interface OnboardingTourProps {
  isOpen: boolean;
  onClose: () => void;
  onSwitchSection: (section: string) => void;
}

export const OnboardingTour: React.FC<OnboardingTourProps> = ({
  isOpen,
  onClose,
  onSwitchSection
}) => {
  const [currentStepIndex, setCurrentStepIndex] = React.useState(0);

  const step = TOUR_STEPS[currentStepIndex];

  // Auto-switch sections when stepping through the tour
  useEffect(() => {
    if (isOpen && step) {
      onSwitchSection(step.targetSection);
    }
  }, [isOpen, currentStepIndex, step, onSwitchSection]);

  // Keyboard navigation
  useEffect(() => {
    if (!isOpen) return;

    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'ArrowRight' || e.key === 'Enter') {
        if (currentStepIndex < TOUR_STEPS.length - 1) {
          setCurrentStepIndex(prev => prev + 1);
        } else {
          onClose();
        }
      } else if (e.key === 'ArrowLeft') {
        if (currentStepIndex > 0) {
          setCurrentStepIndex(prev => prev - 1);
        }
      } else if (e.key === 'Escape') {
        onClose();
      }
    };

    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isOpen, currentStepIndex, onClose]);

  if (!isOpen) return null;

  const progressPercent = Math.round(((currentStepIndex + 1) / TOUR_STEPS.length) * 100);

  return (
    <div className="fixed inset-0 z-50 pointer-events-none flex flex-col justify-end sm:justify-center items-center p-3 sm:p-4 bg-slate-900/30 backdrop-blur-[2px]">
      <div className="pointer-events-auto brutal-card w-full max-w-xl bg-white border-2 border-slate-900 shadow-brutal-lg p-5 sm:p-6 space-y-4 animate-in fade-in zoom-in-95 duration-200">
        {/* Top Header Row */}
        <div className="flex items-center justify-between gap-3 border-b-2 border-slate-900/10 pb-3">
          <div className="flex items-center space-x-2">
            <span className="text-[10px] font-black uppercase tracking-wider px-2.5 py-0.5 rounded-full bg-slate-900 text-white">
              Step {step.step} of {TOUR_STEPS.length}
            </span>
            <span className={`text-[10px] font-black uppercase tracking-wider px-2 py-0.5 rounded-full ${step.colorBg} text-slate-900 border border-slate-900`}>
              {step.category}
            </span>
          </div>

          <div className="flex items-center space-x-1.5">
            <button
              onClick={() => setCurrentStepIndex(0)}
              title="Restart Tour from Step 1"
              className="p-1 rounded-lg text-slate-500 hover:text-slate-900 hover:bg-slate-100 transition"
            >
              <RotateCcw className="w-4 h-4" />
            </button>
            <button
              onClick={onClose}
              title="Close Tour (Esc)"
              className="p-1 rounded-lg text-slate-500 hover:text-slate-900 hover:bg-slate-100 transition"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>

        {/* Progress Bar */}
        <div className="w-full bg-slate-100 h-2 rounded-full border border-slate-900 overflow-hidden">
          <div
            className="bg-[#22C55E] h-full transition-all duration-300"
            style={{ width: `${progressPercent}%` }}
          />
        </div>

        {/* Main Content Body */}
        <div className="space-y-3">
          <div className="flex items-start space-x-3">
            <div className={`w-10 h-10 rounded-xl ${step.colorBg} border-2 border-slate-900 flex items-center justify-center shrink-0 shadow-[2px_2px_0px_#1E293B]`}>
              {step.icon}
            </div>
            <div>
              <h3 className="text-base sm:text-lg font-black text-slate-900 leading-snug">
                {step.title}
              </h3>
              <p className="text-xs sm:text-sm text-slate-600 font-medium leading-relaxed mt-1">
                {step.content}
              </p>
            </div>
          </div>

          {/* Key Takeaway Banner */}
          <div className="p-2.5 rounded-xl bg-[#FAF7F2] border-2 border-slate-900/40 text-[11px] font-bold text-slate-800 flex items-center space-x-2">
            <span className="text-[10px] uppercase font-black px-1.5 py-0.5 rounded bg-[#DCFCE7] text-[#15803D] border border-slate-900">
              Key Insight
            </span>
            <span className="truncate">{step.keyTakeaway}</span>
          </div>
        </div>

        {/* Step Dots Indicator */}
        <div className="flex items-center justify-center gap-1.5 pt-1">
          {TOUR_STEPS.map((s, idx) => (
            <button
              key={s.step}
              onClick={() => setCurrentStepIndex(idx)}
              className={`h-2 rounded-full transition-all ${
                idx === currentStepIndex
                  ? 'w-6 bg-slate-900'
                  : 'w-2 bg-slate-200 hover:bg-slate-400'
              }`}
              title={`Jump to Step ${s.step}: ${s.title}`}
            />
          ))}
        </div>

        {/* Bottom Actions Bar */}
        <div className="flex items-center justify-between pt-2 border-t-2 border-slate-900/10">
          <button
            onClick={onClose}
            className="text-xs font-bold text-slate-500 hover:text-slate-900 px-2 py-1"
          >
            Skip Tour
          </button>

          <div className="flex items-center space-x-2">
            <button
              onClick={() => setCurrentStepIndex(prev => Math.max(0, prev - 1))}
              disabled={currentStepIndex === 0}
              className="px-3 py-1.5 rounded-xl border-2 border-slate-900 text-xs font-bold text-slate-900 hover:bg-slate-100 disabled:opacity-40 transition flex items-center space-x-1"
            >
              <ChevronLeft className="w-3.5 h-3.5" />
              <span>Back</span>
            </button>

            {currentStepIndex < TOUR_STEPS.length - 1 ? (
              <button
                onClick={() => setCurrentStepIndex(prev => prev + 1)}
                className="brutal-btn-primary px-4 py-1.5 rounded-xl text-xs font-black flex items-center space-x-1"
              >
                <span>Next Step</span>
                <ChevronRight className="w-3.5 h-3.5" />
              </button>
            ) : (
              <button
                onClick={onClose}
                className="brutal-btn-primary px-4 py-1.5 rounded-xl text-xs font-black flex items-center space-x-1 bg-[#16A34A]"
              >
                <span>Explore App</span>
                <CheckCircle2 className="w-3.5 h-3.5 text-white" />
              </button>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};
